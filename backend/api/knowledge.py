def _matches(text: str, patterns: list[str]) -> bool:
    """مطابقة عربية بالاحتواء، ولاتينية بحدود الكلمات (حتى لا تطابق "rag" داخل "storage")."""
    for p in patterns:
        if p.isascii():
            if re.search(rf'(?<![a-z0-9]){re.escape(p)}(?![a-z0-9])', text):
                return True
        elif p in text:
            return True
    return False


